# =====================================================================
# NUMERIC HELPERS
# =====================================================================

def clean_number(value: Any) -> float | None:
    """
    Convert a value into a JSON-safe finite float.

    Returns:
        float  -> valid finite number
        None   -> missing/invalid/NaN/infinite value
    """

    if value is None:
        return None

    try:
        number = float(value)

    except (TypeError, ValueError):
        return None

    if not math.isfinite(number):
        return None

    return number


def clean_integer(value: Any) -> int | None:
    """
    Convert a numeric value into a safe integer.

    Used primarily for volume.
    """

    number = clean_number(value)

    if number is None:
        return None

    try:
        return int(number)

    except (TypeError, ValueError, OverflowError):
        return None


# =====================================================================
# SYMBOL HELPERS
# =====================================================================

def normalize_symbol(symbol: str) -> str:
    """
    Convert an application stock symbol into an NSE Yahoo symbol.

    Examples:

        WIPRO
            -> WIPRO.NS

        WIPRO.NS
            -> WIPRO.NS

        tcs
            -> TCS.NS

        RELIANCE.NS
            -> RELIANCE.NS
    """

    cleaned = str(symbol or "").strip().upper()

    if not cleaned:
        raise HTTPException(
            status_code=400,
            detail="Stock symbol is required.",
        )

    cleaned = cleaned.strip()

    # Yahoo NSE symbols use .NS.
    if not cleaned.endswith(".NS"):
        cleaned = f"{cleaned}.NS"

    # Avoid malformed symbols such as:
    # ABC.NS.NS
    while cleaned.endswith(".NS.NS"):
        cleaned = cleaned[:-3]

    return cleaned


def display_symbol(symbol: str) -> str:
    """
    Convert a Yahoo NSE symbol into the application's display symbol.

    Example:

        WIPRO.NS -> WIPRO
    """

    normalized = normalize_symbol(symbol)

    return normalized[:-3]


def get_company_name(symbol: str) -> str:
    """
    Return a known company name or fall back to the display symbol.
    """

    base_symbol = display_symbol(symbol)

    return COMPANY_NAMES.get(
        base_symbol,
        base_symbol,
    )


# =====================================================================
# CACHE HELPERS
# =====================================================================

def get_cached_quote(
    symbol: str,
) -> dict[str, Any] | None:
    """
    Return a cached quote if it is still within the TTL.
    """

    now = time.monotonic()

    with _CACHE_LOCK:
        cached = _CACHE.get(symbol)

        if cached is None:
            return None

        cached_at, payload = cached

        if (
            now - cached_at
            >= CACHE_TTL_SECONDS
        ):
            _CACHE.pop(
                symbol,
                None,
            )

            return None

        # Return a copy so callers cannot mutate
        # the cached dictionary accidentally.
        return dict(payload)


def set_cached_quote(
    symbol: str,
    payload: dict[str, Any],
) -> None:
    """
    Store a quote in the local cache.
    """

    with _CACHE_LOCK:
        _CACHE[symbol] = (
            time.monotonic(),
            dict(payload),
        )


def clear_market_cache() -> None:
    """
    Clear all cached market quotes.

    Kept as a helper for development/testing.
    """

    with _CACHE_LOCK:
        _CACHE.clear()


# =====================================================================
# HISTORY
# =====================================================================

def get_latest_history(
    ticker: yf.Ticker,
):
    """
    Retrieve recent daily market observations.

    IMPORTANT:
        This is latest available daily market data from yfinance.
        It is not an official NSE real-time exchange feed.
    """

    try:
        history = ticker.history(
            period=HISTORY_PERIOD,
            interval=HISTORY_INTERVAL,
            auto_adjust=False,
            actions=False,
            repair=True,
            timeout=YFINANCE_TIMEOUT_SECONDS,
        )

    except Exception as exc:
        raise HTTPException(
            status_code=502,
            detail=(
                "Unable to retrieve market data "
                "from the configured provider."
            ),
        ) from exc

    if history is None or history.empty:
        raise HTTPException(
            status_code=404,
            detail=(
                "No market data was returned "
                "for this symbol."
            ),
        )

    if "Close" not in history.columns:
        raise HTTPException(
            status_code=502,
            detail=(
                "Market data response does not "
                "contain a Close price."
            ),
        )

    history = history.dropna(
        subset=["Close"],
        how="all",
    )

    if history.empty:
        raise HTTPException(
            status_code=404,
            detail=(
                "No valid market price was "
                "returned for this symbol."
            ),
        )

    latest = history.iloc[-1]

    previous = None

    if len(history) >= 2:
        previous = history.iloc[-2]

    return (
        history,
        latest,
        previous,
    )


# =====================================================================
# DATE/TIME
# =====================================================================

def serialize_market_date(
    history: Any,
) -> str | None:
    """
    Convert the latest historical index into an ISO string.
    """

    try:
        market_date = history.index[-1]

        if hasattr(
            market_date,
            "to_pydatetime",
        ):
            market_date = (
                market_date.to_pydatetime()
            )

        if isinstance(
            market_date,
            datetime,
        ):
            return market_date.isoformat()

        return str(market_date)

    except Exception:
        return None


def current_timestamp() -> str:
    """
    Return the current timezone-aware local timestamp.
    """

    return (
        datetime.now()
        .astimezone()
        .isoformat()
    )


# =====================================================================
# QUOTE BUILDER
# =====================================================================

def build_quote(
    symbol: str,
) -> dict[str, Any]:
    """
    Retrieve and normalize the latest available market quote.

    This is the single source of truth used by the quote routes
    and the Dashboard snapshot route.
    """

    requested_symbol = (
        str(symbol or "")
        .strip()
        .upper()
    )

    if not requested_symbol:
        raise HTTPException(
            status_code=400,
            detail="Stock symbol is required.",
        )

    yahoo_symbol = normalize_symbol(
        requested_symbol
    )

    # ---------------------------------------------------------------
    # CACHE
    # ---------------------------------------------------------------

    cached = get_cached_quote(
        yahoo_symbol
    )

    if cached is not None:
        cached["cached"] = True

        return cached

    # ---------------------------------------------------------------
    # PROVIDER
    # ---------------------------------------------------------------

    try:
        ticker = yf.Ticker(
            yahoo_symbol
        )

        (
            history,
            latest,
            previous,
        ) = get_latest_history(
            ticker
        )

    except HTTPException:
        raise

    except Exception as exc:
        raise HTTPException(
            status_code=502,
            detail=(
                "Market data provider "
                "error."
            ),
        ) from exc

    # ---------------------------------------------------------------
    # LATEST VALUES
    # ---------------------------------------------------------------

    close = clean_number(
        latest.get("Close")
    )

    open_price = clean_number(
        latest.get("Open")
    )

    high = clean_number(
        latest.get("High")
    )

    low = clean_number(
        latest.get("Low")
    )

    volume = clean_integer(
        latest.get("Volume")
    )

    if close is None:
        raise HTTPException(
            status_code=404,
            detail=(
                f"Latest market price is "
                f"unavailable for "
                f"{requested_symbol}."
            ),
        )

    # ---------------------------------------------------------------
    # PREVIOUS CLOSE
    # ---------------------------------------------------------------

    previous_close = None

    if previous is not None:
        previous_close = clean_number(
            previous.get("Close")
        )

    # ---------------------------------------------------------------
    # CHANGE
    # ---------------------------------------------------------------

    change = None
    change_percent = None

    if (
        previous_close is not None
        and previous_close != 0
    ):
        change = (
            close
            - previous_close
        )

        change_percent = (
            change
            / previous_close
        ) * 100.0

    # ---------------------------------------------------------------
    # MARKET DATE
    # ---------------------------------------------------------------

    market_date = serialize_market_date(
        history
    )

    # ---------------------------------------------------------------
    # RESPONSE
    # ---------------------------------------------------------------

    payload: dict[str, Any] = {
        # Application symbol
        "symbol": display_symbol(
            yahoo_symbol
        ),

        # Yahoo symbol
        "yahoo_symbol": yahoo_symbol,

        # Company information
        "company": get_company_name(
            yahoo_symbol
        ),

        # Price information
        "price": close,
        "previous_close": previous_close,

        "change": clean_number(
            change
        ),

        "change_percent": clean_number(
            change_percent
        ),

        # OHLC
        "open": open_price,
        "high": high,
        "low": low,

        # Explicit aliases useful to UI components
        "day_high": high,
        "day_low": low,

        # Volume
        "volume": volume,

        # Market date
        "market_date": market_date,

        # Provider metadata
        "source": (
            "Yahoo Finance via yfinance"
        ),

        "source_type": (
            "market-data-provider"
        ),

        "provider": "yfinance",

        # This endpoint intentionally does not claim
        # to be an official exchange feed.
        "official_exchange_feed": False,

        "delayed_or_latest_available": True,

        # Current implementation uses daily observations.
        "interval": HISTORY_INTERVAL,

        "period": HISTORY_PERIOD,

        # Status
        "status": "ok",

        # Cache status
        "cached": False,

        # Retrieval timestamp
        "retrieved_at": current_timestamp(),
    }

    set_cached_quote(
        yahoo_symbol,
        payload,
    )

    return payload


# =====================================================================
# DASHBOARD SNAPSHOT HELPERS
# =====================================================================

def fetch_snapshot_quote(
    symbol: str,
) -> dict[str, Any] | None:
    """
    Fetch one monitored stock for the Dashboard snapshot.

    A failure for one stock is intentionally isolated so that
    one unavailable provider response does not make all other
    valid market quotes disappear.
    """

    try:
        return build_quote(symbol)

    except HTTPException:
        return None

    except Exception:
        return None


