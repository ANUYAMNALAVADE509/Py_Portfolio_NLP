# =====================================================================
# DASHBOARD MARKET SNAPSHOT
# =====================================================================

@router.get("/snapshot")
def market_snapshot(
    refresh: bool = Query(
        False,
        description=(
            "Clear the local market cache "
            "before retrieving the snapshot."
        ),
    ),
) -> dict[str, Any]:
    """
    Return the latest available market information for
    the complete QuantRisk AI monitored universe.

    This endpoint is used by Dashboard.jsx.

    The Dashboard expects:

        /api/market/snapshot

    The response contains:

        status
        updated_at
        requested_symbols
        available_symbols
        advancing
        declining
        unchanged
        quotes

    No artificial market values are generated.
    """

    # ---------------------------------------------------------------
    # OPTIONAL FORCE REFRESH
    # ---------------------------------------------------------------

    if refresh:
        clear_market_cache()

    # ---------------------------------------------------------------
    # FETCH ALL 49 SYMBOLS
    # ---------------------------------------------------------------

    successful_quotes: list[dict[str, Any]] = []

    with ThreadPoolExecutor(
        max_workers=SNAPSHOT_MAX_WORKERS
    ) as executor:

        futures = {
            executor.submit(
                fetch_snapshot_quote,
                symbol,
            ): symbol
            for symbol in MONITORED_SYMBOLS
        }

        for future in as_completed(futures):

            try:
                quote = future.result()

            except Exception:
                quote = None

            if quote is not None:
                successful_quotes.append(
                    quote
                )

    # ---------------------------------------------------------------
    # STABLE ORDER
    # ---------------------------------------------------------------

    # Thread completion order is not deterministic.
    # Reorder the valid results according to the
    # monitored portfolio universe.
    order = {
        symbol: index
        for index, symbol
        in enumerate(
            MONITORED_SYMBOLS
        )
    }

    successful_quotes.sort(
        key=lambda quote: order.get(
            quote.get("symbol"),
            len(MONITORED_SYMBOLS),
        )
    )

    # ---------------------------------------------------------------
    # MARKET MOVEMENT COUNTS
    # ---------------------------------------------------------------

    advancing = 0
    declining = 0
    unchanged = 0

    for quote in successful_quotes:

        change = clean_number(
            quote.get("change")
        )

        if change is None:
            continue

        if change > 0:
            advancing += 1

        elif change < 0:
            declining += 1

        else:
            unchanged += 1

    # ---------------------------------------------------------------
    # STATUS
    # ---------------------------------------------------------------

    requested_count = len(
        MONITORED_SYMBOLS
    )

    available_count = len(
        successful_quotes
    )

    if available_count == requested_count:
        status = "available"

    elif available_count > 0:
        status = "partial"

    else:
        status = "unavailable"

    # ---------------------------------------------------------------
    # RESPONSE
    # ---------------------------------------------------------------

    return {
        "status": status,

        "updated_at": current_timestamp(),

        "requested_symbols": requested_count,

        "available_symbols": available_count,

        "advancing": advancing,

        "declining": declining,

        "unchanged": unchanged,

        "quotes": successful_quotes,

        # Provider information
        "source": (
            "Yahoo Finance via yfinance"
        ),

        "provider": "yfinance",

        "official_exchange_feed": False,

        "delayed_or_latest_available": True,

        "interval": HISTORY_INTERVAL,

        "period": HISTORY_PERIOD,

        # Development/cache information
        "cache_ttl_seconds": (
            CACHE_TTL_SECONDS
        ),

        "refresh_requested": refresh,
    }


